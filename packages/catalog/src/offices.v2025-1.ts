interface OfficeSeed {
  readonly code: string;
  readonly department: string;
  readonly names: LocalizedText;
  readonly purpose: LocalizedText;
  readonly section: string;
  readonly pages: readonly number[];
  readonly aliases?: readonly LocalizedText[];
  readonly responsibility?: LocalizedText;
  readonly reportsTo?: string | null;
  readonly mechanism?: AppointmentMechanism;
  readonly minimum?: number;
  readonly maximum?: number | null;
  readonly conditions?: readonly LocalizedText[];
  readonly status?: SourceReviewStatus;
  readonly linkedBase?: string | null;
  readonly applies?: boolean;
  readonly ruleIds?: readonly string[];
  readonly notes?: LocalizedText;
}

const office = (seed: OfficeSeed): OfficeDefinition => ({
  canonicalCode: seed.code,
  departmentCode: seed.department,
  names: seed.names,
  aliases: seed.aliases ?? noAliases,
  purpose: seed.purpose,
  responsibilities: [seed.responsibility ?? scopedResponsibility(seed), mechanismResponsibility(seed)],
  reportsToOfficeCode: seed.reportsTo ?? seed.linkedBase ?? null,
  mechanism: seed.mechanism ?? "church_election_after_nominating_report",
  cardinality: {
    minimum: seed.minimum ?? 0,
    maximum: seed.maximum ?? null,
    homogeneousVacancies: true,
  },
  conditions: seed.conditions ?? ((seed.applies ?? false) ? noConditions : [optionalOfficeCondition]),
  sourceRuleIds: seed.ruleIds ?? ["NM-001", "NM-009"],
  sourceLocators: seed.pages.length === 0 ? [] : sourceLocators(seed.section, seed.pages),
  territory: "worldwide_manual_subject_to_applicable_regional_supplements",
  catalogVersion: CATALOG_PACKAGE_VERSION,
  reviewStatus: seed.status ?? "verified_primary_source",
  linkedBaseOfficeCode: seed.linkedBase ?? null,
  applicableByDefault: seed.applies ?? false,
  notes:
    seed.notes ??
    l(
      "La ficha es un resumen operativo; consultar la fuente original.",
      "This record is an operating summary; consult the original source.",
      "Cette fiche est un résumé opérationnel; consulter la source originale.",
    ),
});

