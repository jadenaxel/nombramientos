const l = (es: string, en: string, fr: string): LocalizedText => ({ es, en, fr });

const noAliases: readonly LocalizedText[] = [];
const noConditions: readonly LocalizedText[] = [];

const ref = (chapter: string, section: string, printedPages: readonly number[]): SourceLocator => ({
  sourceId: "SDA_CM_2025_EN",
  chapter,
  section,
  printedPages,
  pdfPages: printedPages,
  sourceLanguage: "en",
  url: "https://gc.adventist.org/wp-content/uploads/2025/10/Seventh-day_Adventist_Church_Manual-2025-10-13.pdf",
});

const sourceLocators = (section: string, printedPages: readonly number[]): readonly SourceLocator[] => {
  const ordinaryPages = printedPages.filter((page) => page >= 80 && page <= 119);
  const electionPages = printedPages.filter((page) => page >= 120 && page < 190);
  const otherNotesPages = printedPages.filter((page) => page === 190);
  const chapter10NotesPages = printedPages.filter((page) => page === 191 || page === 192);
  const sectionParts = section.split(";").map((part) => part.trim()).filter(Boolean);
  const ordinarySection = sectionParts.filter((part) => !/\b(?:notes?|sample list|work of the nominating committee)\b/iu.test(part)).join("; ") || section;
  const electionSection = sectionParts.find((part) => /work of the nominating committee/iu.test(part)) ?? section;
  const otherNotesSection = sectionParts.find((part) => /notes?/iu.test(part)) ?? section;

  return [
    ...(ordinaryPages.length === 0 ? [] : [ref("Chapter 9 — Local Church Officers and Organizations", ordinarySection, ordinaryPages)]),
    ...(electionPages.length === 0 ? [] : [ref("Chapter 10 — Elections", electionSection, electionPages)]),
    ...(otherNotesPages.length === 0 ? [] : [ref("Chapter 9 Notes", otherNotesSection, otherNotesPages)]),
    ...(chapter10NotesPages.length === 0 ? [] : [ref("Chapter 10 Notes", "1. Sample List of Church Leaders (see p. 122).", chapter10NotesPages)]),
  ];
};

